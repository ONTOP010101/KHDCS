-- 客户资料表
CREATE TABLE IF NOT EXISTS `customers` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `customer_code` VARCHAR(50) DEFAULT NULL COMMENT '客户编号',
  `customer_name` VARCHAR(100) DEFAULT NULL COMMENT '客户名称',
  `country` VARCHAR(50) DEFAULT NULL COMMENT '国家',
  `address` VARCHAR(200) DEFAULT NULL COMMENT '地址',
  `contact_person1` VARCHAR(50) DEFAULT NULL COMMENT '联系人1',
  `mobile1` VARCHAR(20) DEFAULT NULL COMMENT '手机1',
  `phone1` VARCHAR(20) DEFAULT NULL COMMENT '电话1',
  `email` VARCHAR(100) DEFAULT NULL COMMENT '邮箱',
  `qq` VARCHAR(20) DEFAULT NULL COMMENT 'QQ',
  `modifier` VARCHAR(50) DEFAULT NULL COMMENT '修改人',
  `contact_person2` VARCHAR(50) DEFAULT NULL COMMENT '联系人2',
  `mobile2` VARCHAR(20) DEFAULT NULL COMMENT '手机2',
  `phone2` VARCHAR(20) DEFAULT NULL COMMENT '电话2',
  `remark1` VARCHAR(200) DEFAULT NULL COMMENT '备注1',
  `registrant` VARCHAR(50) DEFAULT NULL COMMENT '登记人',
  `contact_person3` VARCHAR(50) DEFAULT NULL COMMENT '联系人3',
  `mobile3` VARCHAR(20) DEFAULT NULL COMMENT '手机3',
  `phone3` VARCHAR(20) DEFAULT NULL COMMENT '电话3',
  `remark2` VARCHAR(200) DEFAULT NULL COMMENT '备注2',
  `region` VARCHAR(50) DEFAULT NULL COMMENT '地区',
  `sms_number` VARCHAR(50) DEFAULT NULL COMMENT '短信号码',
  `register_date` VARCHAR(50) DEFAULT NULL COMMENT '登记日期',
  `modify_date` VARCHAR(50) DEFAULT NULL COMMENT '修改日期',
  `certificate` VARCHAR(100) DEFAULT NULL COMMENT '营业执照',
  `create_by` BIGINT DEFAULT NULL COMMENT '创建人',
  `update_by` BIGINT DEFAULT NULL COMMENT '修改人ID',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` TINYINT DEFAULT 0 COMMENT '逻辑删除',
  PRIMARY KEY (`id`),
  KEY `idx_customer_code` (`customer_code`),
  KEY `idx_customer_name` (`customer_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='客户资料表';
